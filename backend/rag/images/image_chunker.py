"""Caption/OCR-Based Image Chunking.

Each valid image becomes one retrievable chunk whose text combines every
piece of evidence about it, each part labelled by provenance:

    extracted metadata  - alt text, title, caption, filename, page, heading
    extracted OCR text  - text read from the pixels
    surrounding text    - neighbouring paragraphs on the source page
    AI description      - optional, generated by a vision model

Keywords are derived from the extracted fields only (never from the AI
description) so filtering never depends on generated content.
"""

from __future__ import annotations

import re
from collections import Counter

from rag.extraction.html_extractor import humanize_filename
from rag.models import ImageChunk, ImageRecord
from rag.utils import sha256_text

_STOP = {
    "the", "and", "for", "with", "from", "that", "this", "are", "was", "image", "images", "photo", "jpg", "png", "jpeg",
    "webp", "img", "college", "page", "home", "our", "your", "into", "will", "have", "has", "new", "copy", "scaled",
}


def extract_keywords(record: ImageRecord, limit: int = 12) -> list[str]:
    sources = [record.alt, record.title, record.caption, humanize_filename(record.filename), record.heading, record.ocr_text]
    words = re.findall(r"[A-Za-z][A-Za-z0-9&+-]{2,}", " ".join(sources).lower())
    counts = Counter(w for w in words if w not in _STOP)
    return [w for w, _ in counts.most_common(limit)]


def build_image_text(record: ImageRecord) -> str:
    parts = [f"Image on page: {record.page_title}".strip()]
    if record.heading_path:
        parts.append("Section: " + " > ".join(record.heading_path))
    if record.alt:
        parts.append(f"Alt text: {record.alt}")
    if record.title:
        parts.append(f"Title: {record.title}")
    if record.caption:
        parts.append(f"Caption: {record.caption}")
    name = humanize_filename(record.filename)
    if name:
        parts.append(f"Filename: {name}")
    if record.ocr_text:
        parts.append(f"Text in image (OCR): {record.ocr_text}")
    if record.context:
        parts.append(f"Nearby text: {record.context}")
    if record.description:
        parts.append(f"AI-generated description: {record.description}")
    if record.keywords:
        parts.append("Keywords: " + ", ".join(record.keywords))
    return "\n".join(parts)


def has_searchable_evidence(record: ImageRecord) -> bool:
    """An image with no alt/caption/OCR/context/description cannot be retrieved reliably."""
    return any([record.alt, record.caption, record.title, record.ocr_text, record.description, record.context,
                len(humanize_filename(record.filename)) > 3])


def build_image_chunk(record: ImageRecord) -> ImageChunk:
    text = build_image_text(record)
    return ImageChunk(
        chunk_id=record.image_id,
        image_id=record.image_id,
        url=record.url,
        source_page=record.source_page,
        page_title=record.page_title,
        heading=record.heading,
        text=text,
        content_hash=sha256_text(text),
        metadata={
            "alt": record.alt,
            "caption": record.caption,
            "ocr_text": record.ocr_text,
            "description": record.description,
            "description_model": record.description_model,
            "width": record.width,
            "height": record.height,
            "local_path": record.local_path,
            "mime_type": record.mime_type,
            "keywords": record.keywords,
            "also_on_pages": record.also_on_pages,
        },
    )
